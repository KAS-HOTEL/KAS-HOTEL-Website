'use client';

import { useCallback, useEffect, useState } from 'react';
import { vouchersApi } from '@/lib/api/endpoints/adminTools';
import { Badge, Button, Dialog, Table, type Column, PageHeader } from '@/ui/primitives';
import type { CreateVoucher, Voucher, VoucherAudience, VoucherCustomer, VoucherTier } from '@/lib/domain/adminTools';
import { adminError, useAdminList } from './useAdminList';
import { ListState } from './ListState';
import styles from './AdminTools.module.css';

const STATUSES = ['DRAFT', 'ACTIVE', 'PAUSED', 'EXPIRED'] as const;
/** Statuses staff can filter by: the stored ones plus USED_UP, which is derived from the uses. */
const FILTER_STATUSES = [...STATUSES, 'USED_UP'] as const;

const STATUS_LABEL: Readonly<Record<string, string>> = {
  DRAFT: 'Nháp',
  ACTIVE: 'Đang hoạt động',
  PAUSED: 'Tạm dừng',
  EXPIRED: 'Hết hạn',
  USED_UP: 'Đã dùng hết',
};

const TYPE_LABEL: Readonly<Record<string, string>> = {
  PERCENTAGE: 'Giảm theo %',
  FIXED_AMOUNT: 'Giảm số tiền',
  VALUE_ADD: 'Quyền lợi (cũ)',
};

function statusTone(status: string): 'success' | 'neutral' | 'warning' | 'danger' {
  if (status === 'USED_UP') {
    return 'danger';
  }
  return status === 'ACTIVE' ? 'success' : status === 'PAUSED' ? 'warning' : 'neutral';
}

/** The status shown in the list; older responses without `displayStatus` fall back to the stored one. */
function shownStatus(row: Voucher): string {
  return row.displayStatus ?? row.status;
}

/** Past its last valid day: changing the stored status cannot make it usable again. */
function expiredByDate(row: Voucher): boolean {
  return shownStatus(row) === 'EXPIRED' && row.status !== 'EXPIRED';
}

function formatValue(row: Voucher): string {
  if (row.type === 'PERCENTAGE') {
    return `${row.valuePercent ?? '—'}%`;
  }
  if (row.type === 'FIXED_AMOUNT') {
    return row.valueMinor === null || row.valueMinor === undefined
      ? '—'
      : `${new Intl.NumberFormat('vi-VN').format(row.valueMinor)} ${row.currency}`;
  }
  // A voucher created before the "value add" type was removed still lists.
  return row.valueAddDescription ?? '—';
}

function formatRange(from?: string, to?: string): string {
  if (!from && !to) {
    return 'Không giới hạn';
  }
  return `${from ?? '…'} → ${to ?? '…'}`;
}

/** An instant in hotel time, e.g. `14:05 14/11/2026`. */
export function formatHotelTime(iso?: string | null): string {
  if (!iso) return '';
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  const part = (type: string) => new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Ho_Chi_Minh', hour: '2-digit', minute: '2-digit', day: '2-digit', month: '2-digit', year: 'numeric', hour12: false,
  }).formatToParts(date).find((p) => p.type === type)?.value ?? '';
  return `${part('hour')}:${part('minute')} ${part('day')}/${part('month')}/${part('year')}`;
}

/** Validity: real times when the voucher has them (2026-11-14 on), dates for older ones. */
function formatValidity(row: Voucher): string {
  if (row.validFromAt || row.validToAt) {
    return `${formatHotelTime(row.validFromAt) || '…'} → ${formatHotelTime(row.validToAt) || 'không giới hạn'}`;
  }
  return formatRange(row.validFrom, row.validTo);
}

function formatAudience(row: Voucher): string {
  if (row.audience === 'TIERS') return `Hạng: ${(row.tiers ?? []).map((tier) => tier.name).join(', ') || '—'}`;
  if (row.audience === 'CUSTOMERS') {
    const customers = row.customers ?? [];
    const names = customers.slice(0, NAMED_CUSTOMERS).map((customer) => customer.customerCode ?? customer.fullName).join(', ');
    return `${customers.length} khách: ${names}${customers.length > NAMED_CUSTOMERS ? '…' : ''}`;
  }
  return 'Tất cả khách';
}

/** A datetime-local value without seconds. */
const MINUTES = /^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}$/;
/** How many chosen customers the list names before "…". */
const NAMED_CUSTOMERS = 3;

/** `2026-11-20T18:30` typed in hotel time → `2026-11-20T18:30:00+07:00`. */
function hotelInstant(local: string): string {
  return `${MINUTES.test(local) ? `${local}:00` : local}+07:00`;
}

/**
 * Vouchers. The code is generated by the backend when a voucher is created and
 * shown once it exists; staff never type it. The form keeps only the fields the
 * business uses: name, discount type and value, minimum order, end time (it starts the
 * moment it is created, 2026-11-14), who may use it (everyone, some member tiers or chosen
 * customers), quantity issued, per-customer limit and status.
 */
export function VoucherManager({ hotels = [] }: { readonly hotels?: readonly { readonly slug: string; readonly label: string }[] }) {
  const [filter, setFilter] = useState({ q: '', status: '' });
  const loader = useCallback(() => vouchersApi.list(filter.q, filter.status), [filter]);
  const { rows, loading, error, setError, reload } = useAdminList(loader);
  const [creating, setCreating] = useState(false);
  const [type, setType] = useState<'PERCENTAGE' | 'FIXED_AMOUNT'>('PERCENTAGE');
  const [busy, setBusy] = useState(false);
  const [actionError, setActionError] = useState('');
  const [created, setCreated] = useState<Voucher | null>(null);
  const [scope, setScope] = useState<'all' | 'some'>('all');
  const [audience, setAudience] = useState<VoucherAudience>('ALL');
  const [tiers, setTiers] = useState<VoucherTier[]>([]);
  const [chosen, setChosen] = useState<VoucherCustomer[]>([]);
  const [query, setQuery] = useState('');
  const [found, setFound] = useState<VoucherCustomer[]>([]);

  useEffect(() => {
    if (!creating) return;
    void vouchersApi.tiers().then(setTiers).catch(() => setTiers([]));
  }, [creating]);

  useEffect(() => {
    const q = query.trim();
    if (audience !== 'CUSTOMERS' || q.length < 2) return undefined;
    const timer = setTimeout(() => {
      void vouchersApi.searchCustomers(q).then(setFound).catch(() => setFound([]));
    }, 250);
    return () => clearTimeout(timer);
  }, [query, audience]);

  const columns: readonly Column<Voucher>[] = [
    { key: 'code', header: 'Mã voucher', cell: (row) => <strong className={styles.code}>{row.code}</strong> },
    { key: 'name', header: 'Tên', cell: (row) => row.name },
    {
      key: 'value',
      header: 'Ưu đãi',
      cell: (row) => (
        <span className={styles.stackCell}>
          <span>{formatValue(row)}</span>
          <span className={styles.muted}>{TYPE_LABEL[row.type] ?? row.type}</span>
        </span>
      ),
    },
    {
      key: 'hotels',
      header: 'Khách sạn áp dụng',
      cell: (row) => (row.properties === undefined || row.properties.length === 0
        ? <span className={styles.muted}>Tất cả khách sạn</span>
        : row.properties.map((hotel) => hotel.name).join(', ')),
    },
    { key: 'audience', header: 'Khách áp dụng', cell: (row) => formatAudience(row) },
    { key: 'valid', header: 'Hiệu lực', cell: (row) => formatValidity(row) },
    { key: 'created', header: 'Tạo lúc', cell: (row) => formatHotelTime(row.createdAt) || '—' },
    {
      key: 'usage',
      header: 'Đã dùng',
      align: 'end',
      cell: (row) => `${row.usedCount} / ${row.usageLimitTotal ?? '∞'}`,
    },
    {
      key: 'status',
      header: 'Trạng thái',
      cell: (row) => <Badge tone={statusTone(shownStatus(row))}>{STATUS_LABEL[shownStatus(row)] ?? shownStatus(row)}</Badge>,
    },
    {
      key: 'actions',
      header: <span className="srOnly">Thao tác</span>,
      isActions: true,
      cell: (row) => (
        <select
          className={styles.inlineSelect}
          aria-label={`Đổi trạng thái ${row.code}`}
          value={expiredByDate(row) ? 'EXPIRED' : row.status}
          disabled={busy || expiredByDate(row)}
          title={expiredByDate(row) ? 'Voucher đã quá ngày hiệu lực' : undefined}
          onChange={(event) => {
            const status = event.target.value;
            setBusy(true);
            setError('');
            void vouchersApi
              .setStatus(row.id, status)
              .then(() => reload())
              .catch((caught: unknown) => setError(adminError(caught)))
              .finally(() => setBusy(false));
          }}
        >
          {STATUSES.map((status) => (
            <option key={status} value={status}>
              {STATUS_LABEL[status]}
            </option>
          ))}
        </select>
      ),
    },
  ];

  return (
    <div className={styles.page}>
      <PageHeader
        eyebrow="Ưu đãi"
        title="Voucher"
        description="Mã ưu đãi, thời hạn và giới hạn sử dụng. Mã voucher do hệ thống tự tạo."
        actions={
      <Button
        onClick={() => {
          setCreating(true);
          setActionError('');
          setCreated(null);
          setScope('all');
          setAudience('ALL');
          setChosen([]);
          setQuery('');
          setFound([]);
        }}
        disabled={busy}
      >
        Tạo voucher
      </Button>
        }
      />

      <form
        className={styles.filters}
        aria-label="Tìm voucher"
        onSubmit={(event) => {
          event.preventDefault();
          const data = new FormData(event.currentTarget);
          setFilter({ q: String(data.get('q') ?? ''), status: String(data.get('status') ?? '') });
        }}
      >
        <label>
          Mã hoặc tên
          <input name="q" />
        </label>
        <label>
          Trạng thái
          <select name="status">
            <option value="">Tất cả</option>
            {FILTER_STATUSES.map((status) => (
              <option key={status} value={status}>
                {STATUS_LABEL[status]}
              </option>
            ))}
          </select>
        </label>
        <Button type="submit" disabled={busy}>
          Tìm kiếm
        </Button>
      </form>

      {created === null ? null : (
        <p role="status" className={styles.notice}>
          Đã tạo voucher <strong>{created.code}</strong> · {created.name}
        </p>
      )}

      <div className={styles.resultHeader}>
        <h2>Danh sách voucher</h2>
        {!loading && !error && <span>{rows.length} mã · tối đa 200 kết quả</span>}
      </div>
      {loading || error || rows.length === 0 ? (
        <ListState
          loading={loading}
          error={error}
          onRetry={() => void reload()}
          errorTitle="Chưa tải được voucher"
          emptyTitle="Không có voucher phù hợp"
          emptyDescription="Thử thay đổi bộ lọc hoặc tạo một voucher mới."
        />
      ) : (
        <Table caption="Danh sách voucher" columns={columns} rows={rows} rowKey={(row) => row.id} />
      )}

      <Dialog open={creating} title="Tạo voucher" onClose={() => { if (!busy) setCreating(false); }}>
        <form
          className={styles.form}
          onSubmit={(event) => {
            event.preventDefault();
            const data = new FormData(event.currentTarget);
            const text = (key: string) => String(data.get(key) ?? '').trim();
            const number = (key: string) => (text(key) === '' ? null : Number(text(key)));
            const chosenHotels = data.getAll('hotel').map(String);
            if (scope === 'some' && chosenHotels.length === 0) {
              setActionError('Chọn ít nhất một khách sạn, hoặc áp dụng cho tất cả khách sạn.');
              return;
            }
            const chosenTiers = data.getAll('tier').map(String);
            if (audience === 'TIERS' && chosenTiers.length === 0) {
              setActionError('Chọn ít nhất một hạng thành viên.');
              return;
            }
            if (audience === 'CUSTOMERS' && chosen.length === 0) {
              setActionError('Thêm ít nhất một khách hàng.');
              return;
            }
            const end = text('validToAt');
            if (end && new Date(hotelInstant(end)).getTime() <= Date.now()) {
              setActionError('Thời gian kết thúc phải sau thời điểm hiện tại.');
              return;
            }
            const body: CreateVoucher = {
              name: text('name'),
              type,
              currency: type === 'FIXED_AMOUNT' ? text('currency') : 'VND',
              status: text('status'),
              ...(type === 'PERCENTAGE' ? { valuePercent: number('value') } : { valueMinor: number('value') }),
              ...(end ? { validToAt: hotelInstant(end) } : {}),
              audience,
              ...(audience === 'TIERS' ? { tierIds: chosenTiers } : {}),
              ...(audience === 'CUSTOMERS' ? { customerIds: chosen.map((customer) => customer.id) } : {}),
              minTotalMinor: number('minTotalMinor'),
              usageLimitTotal: number('usageLimitTotal'),
              usageLimitPerCustomer: number('usageLimitPerCustomer'),
              ...(scope === 'some' ? { propertySlugs: chosenHotels } : {}),
            };
            setBusy(true);
            setActionError('');
            void vouchersApi
              .create(body)
              .then(async (voucher) => {
                setCreated(voucher);
                setCreating(false);
                await reload();
              })
              .catch((caught: unknown) => setActionError(adminError(caught)))
              .finally(() => setBusy(false));
          }}
        >
          <p className={styles.formNote}>Mã voucher sẽ được hệ thống tạo tự động sau khi lưu.</p>
          <label>
            Tên voucher
            <input name="name" required maxLength={200} />
          </label>
          <label>
            Loại giảm giá
            <select value={type} onChange={(event) => setType(event.target.value as 'PERCENTAGE' | 'FIXED_AMOUNT')}>
              <option value="PERCENTAGE">Giảm theo %</option>
              <option value="FIXED_AMOUNT">Giảm số tiền</option>
            </select>
          </label>
          <label>
            {type === 'PERCENTAGE' ? 'Giá trị giảm (%)' : 'Giá trị giảm'}
            <input
              key={type}
              name="value"
              type="number"
              required
              min={type === 'PERCENTAGE' ? 0.001 : 0}
              max={type === 'PERCENTAGE' ? 100 : undefined}
              step={type === 'PERCENTAGE' ? 0.001 : 1}
            />
          </label>
          {type === 'FIXED_AMOUNT' ? (
            <label>
              Tiền tệ
              <select name="currency">
                <option>VND</option>
                <option>USD</option>
              </select>
            </label>
          ) : null}
          <label>
            Đơn hàng tối thiểu
            <input type="number" name="minTotalMinor" min={0} step={1} />
          </label>
          <fieldset className={styles.hotelScope}>
            <legend>Khách sạn áp dụng</legend>
            <label className={styles.checkboxField}>
              <input type="radio" name="scope" checked={scope === 'all'} onChange={() => setScope('all')} /> Tất cả khách sạn
            </label>
            <label className={styles.checkboxField}>
              <input type="radio" name="scope" checked={scope === 'some'} onChange={() => setScope('some')} /> Chọn khách sạn
            </label>
            {scope === 'some' ? (
              <div className={styles.hotelChoices}>
                {hotels.length === 0 ? <span className={styles.muted}>Không tải được danh sách khách sạn.</span> : null}
                {hotels.map((hotel) => (
                  <label key={hotel.slug} className={styles.checkboxField}>
                    <input type="checkbox" name="hotel" value={hotel.slug} /> {hotel.label}
                  </label>
                ))}
              </div>
            ) : null}
          </fieldset>
          <fieldset className={styles.hotelScope}>
            <legend>Khách áp dụng</legend>
            <label className={styles.checkboxField}>
              <input type="radio" name="audience" checked={audience === 'ALL'} onChange={() => setAudience('ALL')} /> Tất cả khách
            </label>
            <label className={styles.checkboxField}>
              <input type="radio" name="audience" checked={audience === 'TIERS'} onChange={() => setAudience('TIERS')} /> Theo hạng thành viên
            </label>
            <label className={styles.checkboxField}>
              <input type="radio" name="audience" checked={audience === 'CUSTOMERS'} onChange={() => setAudience('CUSTOMERS')} /> Khách hàng cụ thể
            </label>
            {audience === 'TIERS' ? (
              <div className={styles.hotelChoices}>
                {tiers.length === 0 ? <span className={styles.muted}>Không tải được danh sách hạng thành viên.</span> : null}
                {tiers.map((tier) => (
                  <label key={tier.id} className={styles.checkboxField}>
                    <input type="checkbox" name="tier" value={tier.id} /> {tier.name}
                  </label>
                ))}
              </div>
            ) : null}
            {audience === 'CUSTOMERS' ? (
              <div className={styles.hotelChoices}>
                <label>
                  Tìm khách (mã khách, email hoặc tên)
                  <input type="search" value={query} onChange={(event) => setQuery(event.target.value)} autoComplete="off" />
                </label>
                {(query.trim().length < 2 ? [] : found).filter((customer) => !chosen.some((c) => c.id === customer.id)).map((customer) => (
                  <button key={customer.id} type="button" className={styles.linkButton}
                    onClick={() => { setChosen([...chosen, customer]); setQuery(''); setFound([]); }}>
                    + {customer.customerCode ?? '—'} · {customer.fullName}{customer.email ? ` · ${customer.email}` : ''}
                  </button>
                ))}
                {chosen.length > 0 ? (
                  <ul aria-label="Khách đã chọn" className={styles.chosenList}>
                    {chosen.map((customer) => (
                      <li key={customer.id}>
                        <span>{customer.customerCode ?? '—'} · {customer.fullName}</span>
                        <button type="button" aria-label={`Bỏ ${customer.fullName}`}
                          onClick={() => setChosen(chosen.filter((c) => c.id !== customer.id))}>×</button>
                      </li>
                    ))}
                  </ul>
                ) : <span className={styles.muted}>Chưa chọn khách nào.</span>}
              </div>
            ) : null}
          </fieldset>
          <p className={styles.formNote}>Bắt đầu: ngay khi bấm Tạo voucher (giờ thực).</p>
          <label>
            Ngày giờ kết thúc
            <input type="datetime-local" name="validToAt" />
          </label>
          <label>
            Số lượng phát hành
            <input type="number" name="usageLimitTotal" min={1} step={1} />
          </label>
          <label>
            Giới hạn mỗi khách
            <input type="number" name="usageLimitPerCustomer" min={1} step={1} />
          </label>
          <label>
            Trạng thái
            <select name="status" defaultValue="DRAFT">
              {STATUSES.map((status) => (
                <option key={status} value={status}>
                  {STATUS_LABEL[status]}
                </option>
              ))}
            </select>
          </label>
          {actionError && <p role="alert">{actionError}</p>}
          <Button type="submit" loading={busy} disabled={busy}>
            Tạo voucher
          </Button>
        </form>
      </Dialog>
    </div>
  );
}
