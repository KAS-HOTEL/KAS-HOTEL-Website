import { api } from '../client';
import type {
  AttachMediaRequest,
  MediaAssetView,
  MediaCoverView,
  MediaLinkView,
  MediaOwnerType,
  RegisterMediaRequest,
  UploadUrlView,
} from '@/lib/domain/media';

/**
 * Media endpoints — verified against `media.api.AdminMediaController`.
 *
 * Path and permissions are frozen by doc 58 §8: `/admin/media`, `/{id}/links`,
 * `/{id}/usages`, with `media.upload` for registering, describing, attaching and
 * arranging, and `media.publish` for the acts that can put an image in front of a
 * guest.
 *
 * <h2>Uploading — doc 62 §4</h2>
 *
 * `uploadUrl` then a direct `PUT` then `complete`. **The bytes never go through
 * the Next server or the Spring backend**: doc 62 §4 says the application server
 * never proxies image bytes, so `uploadToStorage` uses a bare `fetch` against the
 * signed URL rather than `api.put`, which would attach KAS cookies and the CSRF
 * header to a third-party origin.
 *
 * <h2>What is not wrapped, and why</h2>
 *
 * `POST /{id}/publish` and `PATCH /{id}/links/{linkId}/status` both require
 * `media.publish`, which a Partner does not hold — publication is a KAS act, as
 * it is for room types. Wrapping them would put a control one import away from a
 * screen that must not have one.
 *
 * `PATCH /{id}/translations` and `PATCH /{id}/links/{linkId}/order` exist and are
 * deliberately left for the screens that need them; alt text and reordering are
 * not what the publish checklist asks for.
 *
 * <h2>A gallery is assembled, not fetched</h2>
 *
 * `/{id}/usages` answers "where is *this asset* used on *this owner*" — it takes
 * the owner as required query parameters — so there is no single "the gallery of
 * property X" request. A gallery is therefore the library plus one usages call
 * per asset: acceptable while a partner's library is small, and it invents no
 * endpoint. See `loadPropertyGallery`.
 */

const BASE = '/api/v1/admin/media';

const asset = (assetId: string) => `${BASE}/${encodeURIComponent(assetId)}`;

export const mediaApi = {
  /**
   * `GET /api/v1/admin/media`
   *
   * The caller's own library. Scope decides whose, so this is never a portfolio
   * listing for someone else, and a partner with no assets gets `[]`.
   */
  library: (cookieHeader?: string) =>
    api.get<MediaAssetView[]>(BASE, cookieHeader === undefined ? {} : { cookieHeader }),

  /**
   * `GET /api/v1/admin/media/covers?ownerType=`
   *
   * The cover of every property — or of every room type — the session reaches,
   * in one request.
   *
   * A gallery is assembled from the library plus one `usages` call per asset,
   * which is right for the single owner a media screen edits and wrong for a
   * portfolio: eight hotels would cost the library eight times over. This
   * answers the list's own question instead, and writes nothing — setting a
   * cover is still `setCover` and nothing else.
   */
  covers: (ownerType: MediaOwnerType, cookieHeader?: string) =>
    api.get<MediaCoverView[]>(`${BASE}/covers`, {
      query: { ownerType },
      ...(cookieHeader === undefined ? {} : { cookieHeader }),
    }),

  /**
   * `POST /api/v1/admin/media`
   *
   * Registers the descriptor and returns it with the id everything else is keyed
   * by. Always `DRAFT`: `media.publish` is a separate permission and a separate
   * request.
   *
   * The storage key is generated by the server and never appears in the request
   * or the response — doc 62 §2 marks it internal.
   */
  register: (body: RegisterMediaRequest) => api.post<MediaAssetView>(BASE, body),

  /**
   * `POST /api/v1/admin/media/upload-url` — doc 62 §4 step 1.
   *
   * Registers the asset and returns a short-lived URL to `PUT` the bytes to. The
   * body is the same `RegisterMediaRequest` as `register`, because it describes
   * the same thing; there is still no `storageKey` field, and the backend would
   * reject one.
   */
  uploadUrl: (body: RegisterMediaRequest, owner?: { ownerType: MediaOwnerType; ownerId: string }) =>
    api.post<UploadUrlView>(`${BASE}/upload-url`, body, owner ? { query: owner } : {}),
  external: (body: { url: string; mimeType: string; category: string; ownerType: MediaOwnerType; ownerId: string; displayOrder: number; altTextVi: string; altTextEn: string }) =>
    api.post<MediaAssetView>(`${BASE}/external`, body),

  /**
   * `POST /api/v1/admin/media/{assetId}/complete` — doc 62 §4 step 3.
   *
   * Confirms the bytes landed. The backend checks the object exists, that its
   * type matches, and that its first bytes really are that type, then records the
   * size and checksum **it** read rather than anything sent from here.
   *
   * Identical bytes uploaded twice return the earlier asset, so a retry is safe.
   */
  complete: (assetId: string) => api.post<MediaAssetView>(`${asset(assetId)}/complete`, undefined),

  /**
   * `GET /api/v1/admin/media/{assetId}/usages?ownerType=&ownerId=`
   *
   * Where this asset is used **on one owner**. Both query parameters are
   * required by the controller: it reads the owner's links and then keeps the
   * ones belonging to this asset, so the answer is always scoped to a single
   * property or room type rather than being a cross-owner listing.
   *
   * That shape is why a gallery is assembled per asset — see
   * `loadPropertyGallery`.
   */
  usages: (
    assetId: string,
    ownerType: MediaOwnerType,
    ownerId: string,
    cookieHeader?: string,
  ) =>
    api.get<MediaLinkView[]>(`${asset(assetId)}/usages`, {
      query: { ownerType, ownerId },
      ...(cookieHeader === undefined ? {} : { cookieHeader }),
    }),

  /**
   * `POST /api/v1/admin/media/{assetId}/links`
   *
   * Places the asset on a property or room type. The new link is **never** the
   * cover — `is_cover` defaults false and the request has no field for it, so a
   * first attachment does not silently become the hero image.
   *
   * **404** when either the asset or the owner is outside the caller's scope.
   */
  attach: (assetId: string, body: AttachMediaRequest) =>
    api.post<MediaLinkView>(`${asset(assetId)}/links`, body),

  /**
   * `PATCH /api/v1/admin/media/{assetId}/links/{linkId}/cover`
   *
   * Makes this placement the owner's cover; any previous cover is cleared by the
   * same request. The database holds the invariant
   * (`UNIQUE (owner_type, owner_id) WHERE is_cover`), so there is no window in
   * which a property has two covers or none.
   */
  setCover: (assetId: string, linkId: string) =>
    api.patch<MediaLinkView>(`${asset(assetId)}/links/${encodeURIComponent(linkId)}/cover`),

  /**
   * `PATCH /api/v1/admin/media/{assetId}/links/{linkId}/order?displayOrder=`
   *
   * Moves one placement within its owner's gallery. `displayOrder` is a
   * position, not a swap: the caller decides the whole sequence and sends each
   * link's new index, which is what makes a drag that moves an item three places
   * express itself as three unambiguous writes rather than three swaps whose
   * order matters.
   *
   * The cover is a separate flag (`setCover`) and is unaffected — a gallery can
   * be reordered without changing which image leads it.
   */
  setOrder: (assetId: string, linkId: string, displayOrder: number) =>
    api.patch<MediaLinkView>(
      `${asset(assetId)}/links/${encodeURIComponent(linkId)}/order`,
      undefined,
      { query: { displayOrder: String(displayOrder) } },
    ),

  /**
   * `DELETE /api/v1/admin/media/{assetId}/links/{linkId}`
   *
   * Removes the placement, not the asset. Detaching the cover leaves the property
   * without one, which is exactly what the publish checklist will then report.
   */
  detach: (assetId: string, linkId: string) =>
    api.delete<void>(`${asset(assetId)}/links/${encodeURIComponent(linkId)}`),
} as const;

/**
 * The direct `PUT` of doc 62 §4 step 2 — browser to storage, nothing in between.
 *
 * A bare `fetch`, deliberately, rather than the `api` client: that client sends
 * KAS session cookies and an `X-XSRF-TOKEN` header, and this request goes to a
 * storage origin that is not KAS. Attaching either would leak them to a third
 * party. The signed URL carries its own authorisation and needs nothing else.
 *
 * `Content-Type` must match what the URL was signed for, or storage rejects the
 * signature. That is the point: one minted URL stores one declared type at one
 * key, and cannot be repurposed.
 *
 * @throws Error when storage refuses the write — the caller turns it into a
 *         message; storage's own body is not shown to a Partner, because it is a
 *         vendor's XML and can name the bucket.
 */
export async function uploadToStorage(
  uploadUrl: string,
  file: File,
  signal?: AbortSignal,
): Promise<void> {
  let response: Response;
  try {
    response = await fetch(uploadUrl, {
      method: 'PUT',
      body: file,
      headers: { 'Content-Type': file.type },
      // `credentials` is left at the platform default, `same-origin`, which sends
      // nothing to a cross-origin host — exactly what is wanted here. Writing
      // `credentials: 'omit'` would say the same thing and trip the source guard
      // that forbids it, and that guard is right to: on a KAS request omitting
      // credentials would break the session, and a rule with an exception is a rule
      // someone copies to the wrong call.
      ...(signal === undefined ? {} : { signal }),
    });
  } catch (caught) {
    // `fetch` rejects — rather than resolving with a bad status — when the
    // request never completed at all. For this call that overwhelmingly means
    // the CORS preflight was refused: a cross-origin PUT carrying Content-Type
    // is not a simple request, so the browser sends OPTIONS first, and object
    // storage answers it only when the bucket has a CORS rule allowing this
    // origin. It is also what an offline browser or a bad host looks like.
    //
    // The distinction matters enough to keep: "storage said no" and "the browser
    // was never allowed to ask" have completely different fixes, and collapsing
    // them into one message is what made this failure undiagnosable.
    throw new StorageUploadError(null, caught);
  }

  if (!response.ok) {
    throw new StorageUploadError(response.status);
  }
}

/**
 * A direct-to-storage upload that did not succeed.
 *
 * Deliberately not an {@link ApiError}: nothing here came from the KAS API, and
 * treating it as one would put a vendor's words in front of a Partner.
 */
export class StorageUploadError extends Error {
  /**
   * The HTTP status storage answered with, or `null` when the request never
   * completed — a refused CORS preflight, or no network at all.
   */
  readonly status: number | null;

  constructor(status: number | null, cause?: unknown) {
    super(status === null
      ? 'the upload never reached storage'
      : `storage rejected the upload (${status})`);
    this.name = 'StorageUploadError';
    this.status = status;
    if (cause !== undefined) {
      this.cause = cause;
    }
  }
}
